// MIX-1689: writes forms.mjs FORMS + PROSE as attack.mjs lines (R = attack, A = twin/prose) to stdout.
import { FORMS, PROSE } from './forms.mjs';
const q = (s) => s.replace(/'/g, '’');
console.log('// MIX-1689 separator allowlist forms (generated by gen-formy.mjs from forms.mjs)');
for (const [id, , a, t] of FORMS) {
  console.log(`  ['${id}', 'R', '${q(a)}'],`);
  console.log(`  ['${id.slice(0, 3)}t', 'A', '${q(t)}'],`);
}
PROSE.forEach((p, i) => console.log(`  ['SP${i + 1} prose', 'A', '${q(p)}'],`));
