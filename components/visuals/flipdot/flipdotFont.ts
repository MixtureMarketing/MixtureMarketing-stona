/** Znaki diakrytyczne: baza + akcent nad glifem / ogonek pod nim. */
const PL: Record<string, { base: string; accent?: 'acute' | 'dot'; tail?: boolean }> = {
  Ą: { base: 'A', tail: true },
  Ć: { base: 'C', accent: 'acute' },
  Ę: { base: 'E', tail: true },
  Ł: { base: 'L' },
  Ń: { base: 'N', accent: 'acute' },
  Ó: { base: 'O', accent: 'acute' },
  Ś: { base: 'S', accent: 'acute' },
  Ź: { base: 'Z', accent: 'acute' },
  Ż: { base: 'Z', accent: 'dot' },
};
// Ł dostaje własny glif (kreska przez trzon, nie akcent).
F['Ł'] = [0x10, 0x10, 0x12, 0x14, 0x18, 0x10, 0x1f];

/**
 * Słowo → macierz bitów LINE_ROWS × N kolumn (true = tarcza zapalona).
 * Znaki spoza matrycy dostają pustą komórkę (odstęp) — brak crashy na
 * nietypowej interpunkcji. Wejście normalizowane do wersalików.
 */
export function rasterWord(word: string): boolean[][] {
  const chars = word.toLocaleUpperCase('pl-PL').split('');
  const cols = chars.length * (CHAR_COLS + 1) - 1;
  const grid: boolean[][] = Array.from({ length: LINE_ROWS }, () =>
    new Array<boolean>(cols).fill(false),
  );
  chars.forEach((ch, i) => {
    const x0 = i * (CHAR_COLS + 1);
    const pl = PL[ch];
    const glyph = F[pl && ch !== 'Ł' ? pl.base : ch];
    if (!glyph) return;
    for (let r = 0; r < GLYPH_ROWS; r++) {
      const bits = glyph[r];
      for (let c = 0; c < CHAR_COLS; c++) {
        if (bits & (1 << (CHAR_COLS - 1 - c))) grid[ACCENT_ROWS + r][x0 + c] = true;
      }
    }
    if (pl?.accent === 'acute') {
      grid[0][x0 + 3] = true;
      grid[1][x0 + 2] = true;
    } else if (pl?.accent === 'dot') {
      grid[0][x0 + 2] = true;
    }
    if (pl?.tail) {
      grid[ACCENT_ROWS + GLYPH_ROWS][x0 + 3] = true;
      grid[ACCENT_ROWS + GLYPH_ROWS][x0 + 4] = true;
    }
  });
  return grid;
}
